#!/usr/bin/env python3
"""render_launcher.py — KEPT scrub transform: live rendered head command -> scripts/launch-vllm-tp4.sh.

usage: python3 scripts/render_launcher.py <rendered-spark5.sh> [out.sh]

Input is the exact `docker run` line the ladder runner rendered for rank 0 (spark5) from spark-ds41f's
config/cluster.laneC.local.json shape tp4-switch-4k (results/<run>/launch-command.txt is a scrubbed copy). The transform
tokenizes it with shlex and replaces, with an assert that each target appears exactly once:
  * container name                 -> $NAME            (default dsv41-karmic-kraken)
  * --env VLLM_HOST_IP=<lan ip>    -> this node's address, resolved from SPARK_HOSTS[rank]
  * SPARKNET_ROCE_PEER_HCAS        -> rebuilt for the rank (keys = the other three ranks), both PFs per peer
  * home-dir model / cache mounts  -> $MODEL_DIR, $DS41F_DIR/cache
  * image                          -> $IMAGE           (default vllm-ds41f-kkref:19f2c20ed4d6-r6x)
  * --node-rank 0                  -> $RANK, plus --headless on ranks 1..3 (what the workers ran; args-check.txt)
  * --master-addr 10.0.0.5         -> $MASTER_ADDR     (head's rail-1 fabric address; documented topology)
Everything else is emitted byte-for-byte (one flag per line, shlex-quoted). Rerun on every launcher change.
"""
import re, shlex, sys

src = open(sys.argv[1]).read().strip()
out = sys.argv[2] if len(sys.argv) > 2 else None
tok = shlex.split(src)
assert tok[:3] == ["docker", "run", "-d"], tok[:3]
assert "--headless" not in tok, "input must be the rank-0 (head) render"

def idx(t):
    hits = [i for i, x in enumerate(tok) if x == t]
    assert len(hits) == 1, (t, len(hits))
    return hits[0]

def idx_re(p):
    hits = [i for i, x in enumerate(tok) if re.fullmatch(p, x)]
    assert len(hits) == 1, (p, len(hits))
    return hits[0]

VAR = {}  # token index -> literal (already-quoted) shell text
VAR[idx("--name") + 1] = '"$NAME"'
assert tok[idx("--name") + 1] == "dsv41-karmic-kraken"
VAR[idx_re(r"VLLM_HOST_IP=\d+\.\d+\.\d+\.\d+")] = '"VLLM_HOST_IP=$VLLM_HOST_IP"'
i = idx_re(r"SPARKNET_ROCE_PEER_HCAS=.*")
assert tok[i] == 'SPARKNET_ROCE_PEER_HCAS={"1":["rocep1s0f0","roceP2p1s0f0"],"2":["rocep1s0f0","roceP2p1s0f0"],"3":["rocep1s0f0","roceP2p1s0f0"]}', tok[i]
VAR[i] = '"SPARKNET_ROCE_PEER_HCAS=$PEER_HCAS"'
VAR[idx_re(r"/home/[^/]+/models/DeepSeek-V4\.1-Flash-1017:/models:ro")] = '"$MODEL_DIR:/models:ro"'
VAR[idx_re(r"/home/[^/]+/models/DeepSeek-V4\.1-Flash-1017:/blobs:ro")] = '"$MODEL_DIR:/blobs:ro"'
VAR[idx_re(r"/home/[^/]+/spark-ds41f/cache:/cache:rw")] = '"$DS41F_DIR/cache:/cache:rw"'
# 2026-10-23: the adopted config mounts two overlays read-only. Scrubbed to $OVERLAY_DIR so the recipe ships
# its own copies (overlays/) instead of pointing at the measuring box.
for _dst, _rel in (
    ("envs.py", "late-admission/vllm/envs.py"),
    ("core.py", "late-admission/vllm/v1/engine/core.py"),
    ("late_admission.py", "late-admission/vllm/v1/worker/gpu/late_admission.py"),
    ("model_runner.py", "late-admission/vllm/v1/worker/gpu/model_runner.py"),
):
    VAR[idx_re(r"/home/[^/]+/laneC-r3/overlays/late-admission/.*/" + _dst + r":/opt/spark3/candidate/vllm/.*:ro")] = \
        f'"$OVERLAY_DIR/{_rel}:$VLLM_TREE/vllm/{_rel.split("late-admission/vllm/")[1]}:ro"'  
VAR[idx_re(r"/home/[^/]+/laneC-r3/overlays/sparknet-0\.5\.0/sparknet:/usr/local/lib/python3\.12/dist-packages/sparknet:ro")] = \
    '"$OVERLAY_DIR/sparknet-0.5.0/sparknet:/usr/local/lib/python3.12/dist-packages/sparknet:ro"'
VAR[idx("vllm-ds41f-kkref:19f2c20ed4d6-r6x")] = '"$IMAGE"'
i = idx("--node-rank"); assert tok[i + 1] == "0"; VAR[i + 1] = '"$RANK"'
i = idx("--master-addr"); assert tok[i + 1] == "10.0.0.5"; VAR[i + 1] = '"$MASTER_ADDR"'
assert tok[-2:] == ["--master-port", "9999"], tok[-2:]

def q(i):
    return VAR.get(i, shlex.quote(tok[i]))

lines, i = [], 3
while i < len(tok):
    t = tok[i]
    if t.startswith("--") and "=" not in t and i + 1 < len(tok) and not tok[i + 1].startswith("--") and tok[i + 1] != tok[idx("vllm-ds41f-kkref:19f2c20ed4d6-r6x")]:
        lines.append(f"{q(i)} {q(i + 1)}"); i += 2
    else:
        lines.append(q(i)); i += 1
body = " \\\n  ".join(["docker run -d"] + lines + ['"${WORKER_FLAGS[@]}"'])

HEAD = r'''#!/usr/bin/env bash
# launch-vllm-tp4.sh — one rank of DeepSeek-V4.1-Flash-1017 on 4x DGX Spark, vLLM fork (spark-ds41f r6x), TP4 over sparknet.
# GENERATED by scripts/render_launcher.py from the live head command of the measured boot (2026-10-23 10:54 UTC,
# arm L20-NET-adopted: late admission @ layer 20 + sparknet 0.5.0 over the 10.5 GiB / 32-seat shape).
# Do not hand-edit; change the render and regenerate.
#
# usage (on each node, workers first: ranks 3, 2, 1, then 0 — scripts/cluster.sh up does this):
#   SPARK_HOSTS="h0 h1 h2 h3" bash launch-vllm-tp4.sh <rank>
# env: SPARK_HOSTS (required; rank order, rank 0 = head; names must resolve on the node), MODEL_DIR
#      (default $HOME/models/DeepSeek-V4.1-Flash-1017), DS41F_DIR (default $HOME/spark-ds41f; its cache/ holds the
#      JIT/AOT caches), MASTER_ADDR (default 10.0.0.5 = head's rail-1 fabric IP), VLLM_HOST_IP (default: resolve
#      SPARK_HOSTS[rank]), IMAGE, NAME, OVERLAY_DIR (default $PWD/overlays — this recipe's own copies of the
#      late-admission files and sparknet 0.5.0), VLLM_TREE (default /opt/spark3/candidate/vllm, the in-image fork
#      tree the overlays shadow).
set -euo pipefail
RANK=${1:?usage: launch-vllm-tp4.sh <rank 0..3>}
read -r -a _H <<<"${SPARK_HOSTS:?set SPARK_HOSTS to 4 hosts, rank order (rank 0 = head)}"
[ "${#_H[@]}" -eq 4 ] || { echo "SPARK_HOSTS needs 4 hosts" >&2; exit 2; }
host(){ echo "${_H[$1]}"; }
NAME=${NAME:-dsv41-karmic-kraken}
IMAGE=${IMAGE:-vllm-ds41f-kkref:19f2c20ed4d6-r6x}
MODEL_DIR=${MODEL_DIR:-$HOME/models/DeepSeek-V4.1-Flash-1017}
DS41F_DIR=${DS41F_DIR:-$HOME/spark-ds41f}
OVERLAY_DIR=${OVERLAY_DIR:-$PWD/overlays}
VLLM_TREE=${VLLM_TREE:-/opt/spark3/candidate/vllm}
MASTER_ADDR=${MASTER_ADDR:-10.0.0.5}
VLLM_HOST_IP=${VLLM_HOST_IP:-$(getent ahostsv4 "$(host "$RANK")" | awk 'NR==1{print $1}')}
[ -n "$VLLM_HOST_IP" ] || { echo "cannot resolve $(host "$RANK")" >&2; exit 2; }
PEER_HCAS=$(python3 -c 'import json,sys; r=int(sys.argv[1]); print(json.dumps({str(p): ["rocep1s0f0", "roceP2p1s0f0"] for p in range(4) if p != r}, separators=(",", ":")))' "$RANK")
WORKER_FLAGS=(); [ "$RANK" -eq 0 ] || WORKER_FLAGS=(--headless)
'''
text = HEAD + body + "\n"
assert not re.search(r"192\.168|/home/|/Users/", text), "unscrubbed host data"
if out:
    open(out, "w").write(text)
else:
    sys.stdout.write(text)
