#!/usr/bin/env python3
"""Trusted oracle parent. Candidate code executes only in a Docker child."""
import json


def grade(returncode, output, expected):
    result = {'ok': False, 'expected_cases': len(expected), 'completed_cases': 0}
    if returncode != 0:
        return {**result, 'error': 'candidate_exit_nonzero'}
    try:
        observed = json.loads(output)
    except (ValueError, TypeError):
        return {**result, 'error': 'candidate_output_not_complete_json'}
    if not isinstance(observed, list):
        return {**result, 'error': 'candidate_output_not_list'}
    result['completed_cases'] = len(observed)
    result['ok'] = json.dumps(observed, sort_keys=True) == json.dumps(expected, sort_keys=True)
    if not result['ok']:
        result['error'] = 'case_mismatch'
    return result


# Fixed public objective checks. Inputs and expected outputs are not generated by
# the contestant. The trusted parent compares values from a separate child.
CASES = {
    'code-slugify': ('slugify.py','slugify',
        [[' Hello, Mars! '],['GPU__Box  42'],['...'],['Mixed.CASE___x'],[''],['a---b']],
        ['hello-mars','gpu-box-42','','mixed-case-x','','a-b']),
    'code-intervals': ('intervals.py','merge_intervals',
        [[[[5,7],[1,3],[2,4],[9,10]]],[[[1,2],[2,5]]],[[]],[[[1,10],[2,3]]],[[[-5,-1],[-2,2]]]],
        [[[1,4],[5,7],[9,10]],[[1,5]],[],[[1,10]],[[-5,2]]]),
    'code-totals': ('totals.py','totals_by_category',
        [['category,amount\na,3\nb,4\na,-1\n'],['category,amount\n'],['category,amount\n\na,7\n\na,2\n'],['category,amount\nz,-5\nx,0\nz,5\n']],
        [{'a':2,'b':4},{},{'a':9},{'z':0,'x':0}]),
    'code-brackets': ('brackets.py','is_balanced',
        [['([{}])'],['([)]'],['notes (v2) [ok]'],[''],['('],[')'],['x{a[b(c)d]e}f']],
        [True,False,True,True,False,False,True]),
}

CHILD = '''import json,runpy,sys
ns=runpy.run_path(sys.argv[1])
fn=ns[sys.argv[2]]
values=[fn(*args) for args in json.loads(sys.argv[3])]
print(json.dumps(values,allow_nan=False))
'''


def main():
    import ctypes, os, pathlib, subprocess, sys
    # This entry point must never execute generated code on the host.
    readonly = bool(os.statvfs('/').f_flag & os.ST_RDONLY)
    if not readonly or os.getenv('NVIDIA_VISIBLE_DEVICES') != 'void' or os.getuid()==0:
        raise SystemExit('Refusing execution outside the explicit unprivileged CPU sandbox')
    # Prevent the candidate child from reopening the trusted parent's stdout via
    # /proc. Only this parent is allowed to emit the evaluator's terminal marker.
    if ctypes.CDLL(None).prctl(4, 0, 0, 0, 0) != 0:
        raise SystemExit('Cannot protect evaluator parent')
    task_id=sys.argv[1]
    if task_id=='__isolation__':
        status=pathlib.Path('/proc/self/status').read_text()
        checks={
            'readonly_root':readonly,
            'unprivileged_user':os.getuid()!=0,
            'no_gpu_devices':not list(pathlib.Path('/dev').glob('nvidia*')),
            'network_none':set(p.name for p in pathlib.Path('/sys/class/net').iterdir())=={'lo'},
            'no_new_privileges':'NoNewPrivs:\t1' in status,
            'no_capabilities':'CapEff:\t0000000000000000' in status,
            'no_docker_socket':not pathlib.Path('/var/run/docker.sock').exists(),
        }
        result={'ok':all(checks.values()),'checks':checks}
    else:
        module,func,inputs,expected=CASES[task_id]
        try:
            p=subprocess.run([sys.executable,'-I','-c',CHILD,'/task/'+module,func,json.dumps(inputs)],
                             capture_output=True,text=True,timeout=5,check=False)
            result=grade(p.returncode,p.stdout,expected)
            result['candidate_stdout']=p.stdout[:4096]
            result['candidate_stderr']=p.stderr[:4096]
        except subprocess.TimeoutExpired:
            result={'ok':False,'error':'candidate_timeout','completed_cases':0}
    print('GAUNTLET_RESULT '+json.dumps(result,sort_keys=True),flush=True)
    return 0 if result['ok'] else 1


if __name__=='__main__':
    raise SystemExit(main())
